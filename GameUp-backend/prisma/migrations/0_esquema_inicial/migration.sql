CREATE OR REPLACE FUNCTION public.fn_exigir_rol()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_col   text   := tg_argv[0];
  v_roles text[] := string_to_array(tg_argv[1], ',');
  v_uid   bigint;
  v_rol   text;
begin
  v_uid := nullif(to_jsonb(new) ->> v_col, '')::bigint;
  if v_uid is null then
    return new;
  end if;
  select r.nombre into v_rol
    from public.usuario u join public.rol r on r.id = u.rol_id
   where u.id = v_uid;
  if v_rol is null or not (v_rol = any (v_roles)) then
    raise exception 'El usuario % no tiene un rol permitido para %.% (permitidos: %)',
      v_uid, tg_table_name, v_col, tg_argv[1] using errcode = '23514';
  end if;
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.fn_intento_antes()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare v_mod_asig bigint; v_mod_act bigint;
begin
  select modulo_id into v_mod_asig from public.asignacion where id = new.asignacion_id;
  select modulo_id into v_mod_act  from public.actividad  where id = new.actividad_id;
  if v_mod_asig is distinct from v_mod_act then
    raise exception 'La actividad % no pertenece al módulo de la asignación %', new.actividad_id, new.asignacion_id
      using errcode = '23514';
  end if;
  if new.numero_intento is null then
    select coalesce(max(numero_intento), 0) + 1 into new.numero_intento
      from public.intento
     where asignacion_id = new.asignacion_id and actividad_id = new.actividad_id;
  end if;
  return new;
end $function$;

