CREATE OR REPLACE FUNCTION public.fn_recalcular_progreso(p_asignacion bigint)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_mod bigint; v_est bigint; v_estado text;
  v_total integer; v_aprob integer; v_prog integer; v_nuevo text;
  v_nom text; v_modnom text;
begin
  select modulo_id, estudiante_id, estado into v_mod, v_est, v_estado
    from public.asignacion where id = p_asignacion;
  if not found then return; end if;

  select count(*) into v_total from public.actividad where modulo_id = v_mod and activa;

  select count(distinct i.actividad_id) into v_aprob
    from public.intento i
    join public.validacion v on v.intento_id = i.id and v.resultado = 'APROBADO'
    join public.actividad a  on a.id = i.actividad_id and a.activa
   where i.asignacion_id = p_asignacion;

  v_prog  := case when v_total = 0 then 0 else least(100, round(100.0 * v_aprob / v_total)::integer) end;
  v_nuevo := case when v_total > 0 and v_prog >= 100 then 'COMPLETADO'
                  when v_estado = 'COMPLETADO' then 'EN_CURSO'
                  else v_estado end;

  update public.asignacion
     set progreso = v_prog, estado = v_nuevo
   where id = p_asignacion
     and (progreso, estado) is distinct from (v_prog, v_nuevo);

  if v_nuevo = 'COMPLETADO' and v_estado <> 'COMPLETADO' then
    select nombre into v_modnom from public.modulo  where id = v_mod;
    select nombres into v_nom   from public.usuario where id = v_est;
    perform public.fn_notificar_acudientes(v_est, 'AVANCE',
      format('%s completó el módulo %s.', v_nom, v_modnom));
  end if;
end $function$;

CREATE OR REPLACE FUNCTION public.fn_validacion_progreso()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare v_intento bigint; v_asig bigint;
begin
  if tg_op = 'DELETE' then v_intento := old.intento_id; else v_intento := new.intento_id; end if;
  select asignacion_id into v_asig from public.intento where id = v_intento;
  if v_asig is not null then
    perform public.fn_recalcular_progreso(v_asig);
  end if;
  return null;
end $function$;

