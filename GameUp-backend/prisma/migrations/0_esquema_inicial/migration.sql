CREATE OR REPLACE FUNCTION public.fn_notificar_acudientes(p_estudiante bigint, p_tipo text, p_mensaje text)
 RETURNS void
 LANGUAGE sql
 SET search_path TO 'public'
AS $function$
  insert into public.notificacion (usuario_id, tipo, mensaje)
  select ae.acudiente_id, p_tipo, p_mensaje
    from public.acudiente_estudiante ae
   where ae.estudiante_id = p_estudiante;
$function$;

CREATE OR REPLACE FUNCTION public.cambiar_nivel(p_estudiante bigint, p_nivel bigint, p_directora bigint, p_motivo text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare v_nivel text; v_nom text;
begin
  select nombre into v_nivel from public.nivel where id = p_nivel;
  if v_nivel is null then
    raise exception 'El nivel % no existe', p_nivel using errcode = '23503';
  end if;
  if not exists (select 1 from public.estudiante where usuario_id = p_estudiante) then
    raise exception 'El estudiante % no existe', p_estudiante using errcode = '23503';
  end if;

  insert into public.historial_nivel (estudiante_id, nivel_id, asignado_por, motivo)
  values (p_estudiante, p_nivel, p_directora, p_motivo);       -- valida que sea directora

  update public.estudiante set nivel_id = p_nivel where usuario_id = p_estudiante;

  select nombres into v_nom from public.usuario where id = p_estudiante;
  perform public.fn_notificar_acudientes(p_estudiante, 'NIVEL',
    format('El nivel de %s cambió a %s.', v_nom, v_nivel));
end $function$;

CREATE OR REPLACE FUNCTION public.fn_act_cont_mismo_modulo()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare v_a bigint; v_c bigint;
begin
  select modulo_id into v_a from public.actividad where id = new.actividad_id;
  select modulo_id into v_c from public.contenido  where id = new.contenido_id;
  if v_a is distinct from v_c then
    raise exception 'La actividad % y el contenido % pertenecen a módulos distintos', new.actividad_id, new.contenido_id
      using errcode = '23514';
  end if;
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.fn_asignacion_antes()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
begin
  if not coalesce((select publicado from public.modulo where id = new.modulo_id), false) then
    raise exception 'El módulo % no está publicado y no puede asignarse', new.modulo_id using errcode = '23514';
  end if;
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.fn_asignacion_despues()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare v_modulo text; v_nombre text;
begin
  select nombre into v_modulo from public.modulo where id = new.modulo_id;
  select nombres into v_nombre from public.usuario where id = new.estudiante_id;
  perform public.fn_notificar_acudientes(new.estudiante_id, 'NUEVO_MODULO',
    format('%s tiene un nuevo módulo asignado: %s.', v_nombre, v_modulo));
  return new;
end $function$;

